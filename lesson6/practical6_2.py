# Завдання 3
# Користувач вводить рядок та число n. Виведіть перші
# n символів. Також виведіть останні n символів.

text = input("Введите строку: ")
n = int(input("Введите число n: "))

if n > len(text):
    print("Ошибка: n слишком велико! В строке только", len(text), "символов.")
else:
    print("Первые", n, "символов:", text[:n])
    print("Последние", n, "символов:", text[-n:])
