# Завдання 1
# Користувач вводить рядок та індекс. Виведіть символ
# під цим індексом. Якщо індекс завеликий, виведіть
# інформацію про помилку.

string = input("Введите строку: ")
index = int(input("Введите индекс: "))

if index >= len(string) or index < 0:
    print("Ошибка: индекс великоват или отрицательный ")
else:
    print("Символ под индексом", index, "это", string[index])

# Завдання 2
# Користувач вводить рядок та два індекси. Виведіть
# зріз рядка. Виправіть помилку в коді

text = input("Введіть рядок: ")

start = int(input("Введіть початковий індекс: "))
end = int(input("Введіть кінцевий індекс: "))

segment = text[start:end]  # проблема была в float и запятой вместо двоеточия

print(segment)

# Завдання 3
# Користувач вводить рядок та число n. Виведіть перші
# n символів. Також виведіть останні n символів.

text = input("Введите строку: ")
n = int(input("Введите число n: "))

if n > len(text):
    print("Ошибка: n слишком велико! В строке только", len(text), "символов.")
else:
    print("Первые", n, "символов:", text[:n])
    print("Последние", n, "символов:", text[-n:])

# Завдання 4
# Користувач вводить рядок. Перевірте чи це
# речення(закінчується на .!?)

text = input("Введите строку:")

if text.endswith((".", "!", "?")):
    print("Это предложение.")
else:
    print("Это не предложение.")

# Завдання 5
# Користувач вводить рядок. Перевірте чи перший
# символ – це велика літера. Виправіть помилку в коді

text = input("Введіть рядок: ")  # .lower() сразу делал все маленькими

if text[0].isupper():  # upper() просто делал букву большой
    print("Перший символ — велика літера")
else:
    print("Перший символ — не велика літера")

# Завдання 6
# Користувач вводить рядок. Перевірте чи це
# паліндром(читається задом наперед так само).
# Приклади: Кіт утік, око, потоп

text = input("Введите строку: ")

# Делает всё маленькими буквами и убирает пробелы
check = text.lower().replace(" ", "")

if check == check[::-1]:
    print("Это палиндром")
else:
    print("Это не палиндром.")
