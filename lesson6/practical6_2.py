# Завдання 1
# Користувач вводить рядок та індекс. Виведіть символ
# під цим індексом. Якщо індекс завеликий, виведіть
# інформацію про помилку.

string = input("Введите строку: ")
index = int(input("Введите индекс: "))

if index >= len(string) or index < 0:
    print("Ошибка: индекс великоват или отрицательный ")
else:
    print("Символ под индексом", index, "это", string[index])

